#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const repositoryRoot = resolve(import.meta.dirname, "../..");
const contractPath = resolve(repositoryRoot, "backend/contracts/worksheet-import-internal-contract/src/main/openapi/openapi.yaml");
const outputPath = resolve(repositoryRoot, "backend/api-gateway/src/main/kotlin/com/playsay/gateway/client/WorksheetImportInternalClient.kt");
const contract = readFileSync(contractPath, "utf8");
const expectedOperations = [
  "createWorksheetImport",
  "getWorksheetImport",
  "cancelWorksheetImport",
  "getWorksheetPagePreview",
  "replaceWorksheetReview",
  "continueWorksheetImportManually",
  "retryWorksheetImportAnalysis",
  "getWorksheetMaterializationBundle",
  "getWorksheetMaterializationAsset",
  "acknowledgeWorksheetMaterialization",
];
const operations = [...contract.matchAll(/^\s+operationId:\s+([^\s]+)\s*$/gm)].map((match) => match[1]);
if (operations.join("\n") !== expectedOperations.join("\n")) {
  throw new Error(`Worksheet internal operations drifted. Expected ${expectedOperations.join(", ")}; found ${operations.join(", ")}`);
}

const generated = `// Generated by scripts/contracts/generate-worksheet-import-client.mjs from the service-owned OpenAPI contract.
// Do not edit by hand.
package com.playsay.gateway.client

import com.fasterxml.jackson.databind.JsonNode
import com.playsay.contract.worksheetimport.model.WorksheetMaterializationBundle
import com.playsay.gateway.dto.WorksheetImportCreateRequest
import java.util.UUID
import org.springframework.web.multipart.MultipartFile

data class WorksheetImportClientContent(val bytes: ByteArray, val contentType: String)

interface WorksheetImportInternalClient {
    fun create(request: WorksheetImportCreateRequest, files: List<MultipartFile>, userBearerToken: String): JsonNode
    fun get(sessionId: UUID, userBearerToken: String): JsonNode
    fun cancel(sessionId: UUID, userBearerToken: String)
    fun preview(sessionId: UUID, pageId: UUID, userBearerToken: String): WorksheetImportClientContent
    fun replaceReview(sessionId: UUID, revision: Long, review: JsonNode, userBearerToken: String): JsonNode
    fun continueManually(sessionId: UUID, userBearerToken: String): JsonNode
    fun retryAnalysis(sessionId: UUID, userBearerToken: String): JsonNode
    fun materializationBundle(sessionId: UUID, revision: Long, rightsConfirmed: Boolean, userBearerToken: String): WorksheetMaterializationBundle
    fun materializationAsset(sessionId: UUID, revision: Long, assetId: UUID, userBearerToken: String): ByteArray
    fun acknowledgeMaterialization(sessionId: UUID, revision: Long, materialId: UUID, userBearerToken: String)
}
`;

if (process.argv.includes("--check")) {
  if (readFileSync(outputPath, "utf8") !== generated) {
    throw new Error("Generated worksheet gateway client is stale; run this script without --check.");
  }
} else {
  writeFileSync(outputPath, generated);
}
